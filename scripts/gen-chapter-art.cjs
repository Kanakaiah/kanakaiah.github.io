// Regenerates src/data/chapterArt.ts from what is actually in public/chapters/.
// Run after adding or removing chapter art:  node scripts/gen-chapter-art.cjs
//
// A generated manifest rather than a runtime check, because the plates live in public/
// and so are invisible to the bundler — nothing can glob them, and the scheduler needs
// the answer synchronously while building the day's plan. An <img onError> fallback is
// too late: by then the card has already claimed to be asking a plate question.

const fs = require('fs');
const path = require('path');

const CHAPTERS_DIR = path.join(__dirname, '..', 'public', 'chapters');
const OUT = path.join(__dirname, '..', 'src', 'data', 'chapterArt.ts');

const counts = {};
for (const book of fs.readdirSync(CHAPTERS_DIR)) {
  const dir = path.join(CHAPTERS_DIR, book);
  if (!fs.statSync(dir).isDirectory()) continue;

  // Highest contiguous chapter from 1. Art has always been drawn in order, and a gap
  // would make a plain count wrong for every chapter past it — better to under-claim
  // than to promise a plate that isn't there.
  const present = new Set(
    fs.readdirSync(dir)
      .map(f => /^ch(\d+)\.png$/.exec(f))
      .filter(Boolean)
      .map(m => Number(m[1]))
  );
  let n = 0;
  while (present.has(n + 1)) n++;
  if (n > 0) counts[book] = n;
}

const entries = Object.keys(counts).sort()
  .map(b => `  ${/^[a-z][a-z0-9]*$/.test(b) ? b : `'${b}'`}: ${counts[b]},`)
  .join('\n');

const total = Object.values(counts).reduce((a, b) => a + b, 0);

fs.writeFileSync(OUT, `// GENERATED by scripts/gen-chapter-art.cjs — do not edit by hand.
//
// How many chapters of each book have artwork, counting from chapter 1. Books with no
// art at all are absent.
//
// This exists because the scheduler has to know, before it builds a card, whether a
// plate can be shown. Asking "what anchors this chapter?" over a picture is a different
// and easier question than asking it cold, and the review history records which was
// asked — so a book with no art silently answering the easy question while logging the
// hard one made that field untrue for a quarter of the canon.
//
// ${Object.keys(counts).length} books, ${total} plates.
export const CHAPTER_ART: Record<string, number> = {
${entries}
};

/** Whether a plate exists for this chapter, and so whether it can be used as a prompt. */
export function hasChapterArt(bookId: string, chapter: number): boolean {
  return chapter >= 1 && chapter <= (CHAPTER_ART[bookId] ?? 0);
}
`);

console.log(`wrote ${OUT}: ${Object.keys(counts).length} books, ${total} plates`);
